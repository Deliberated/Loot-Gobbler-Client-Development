#!/usr/bin/env python3
"""Generates crates/lg-protocol/src/packet_types.rs from RealmShark's PacketType.java (ids, names, directions).

Run from the rust/ folder after the Java enum changed:  python3 tools/gen_packet_types.py
"""
import pathlib
import re

here = pathlib.Path(__file__).resolve().parent.parent
java = here.parent / "vendor/RealmShark-realmshark/src/main/java/packets/PacketType.java"
out = here / "crates/lg-protocol/src/packet_types.rs"

rows = []
for m in re.finditer(r"^\s*([A-Z0-9_]+)\(\s*(\d+),\s*(Incoming|Outgoing)\s*,", java.read_text(), re.M):
    rows.append((int(m.group(2)), m.group(1), m.group(3)))
# ids above 255 (IP_ADDRESS, 1000) are made up by the Java sniffer itself: the game's packet type is one byte
rows = sorted(r for r in rows if r[0] <= 255)
assert len({r[0] for r in rows}) == len(rows), "duplicate packet ids"

lines = [
    "// Generated by tools/gen_packet_types.py from RealmShark's PacketType.java. Do not edit by hand.",
    "",
    "use crate::Direction;",
    "",
    "/// Every packet type the game uses: (id, name, the direction it travels).",
    "pub const PACKET_TYPES: &[(u8, &str, Direction)] = &[",
]
for pid, name, d in rows:
    lines.append(f'    ({pid}, "{name}", Direction::{d}),')
lines += ["];", ""]
out.write_text("\n".join(lines))
print(f"{len(rows)} packet types -> {out.relative_to(here)}")
